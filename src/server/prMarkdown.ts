import sanitizeHtml from "sanitize-html"

// GitHub renders the Markdown; enforce a separate allowlist before it reaches the browser.
export function sanitizePRHtml(html: string): string {
  return sanitizeHtml(html, {
    allowedTags: [
      "p",
      "br",
      "hr",
      "h1",
      "h2",
      "h3",
      "h4",
      "h5",
      "h6",
      "a",
      "strong",
      "em",
      "b",
      "i",
      "s",
      "del",
      "blockquote",
      "pre",
      "code",
      "ul",
      "ol",
      "li",
      "table",
      "thead",
      "tbody",
      "tr",
      "th",
      "td",
      "img",
      "picture",
      "source",
      "details",
      "summary",
      "sub",
      "sup",
      "kbd",
      "div",
      "span",
      "input",
    ],
    allowedAttributes: {
      a: ["href", "title", "target", "rel"],
      img: ["src", "alt", "title", "width", "height", { name: "align", values: ["left", "right"] }],
      source: ["srcset", { name: "media", values: ["(prefers-color-scheme: dark)", "(prefers-color-scheme: light)"] }],
      input: [{ name: "type", values: ["checkbox"] }, "checked", "disabled"],
      ol: ["start"],
      td: ["colspan", "rowspan"],
      th: ["colspan", "rowspan"],
      details: ["open"],
    },
    selfClosing: ["img", "br", "hr", "input", "source"],
    allowedSchemes: ["http", "https", "mailto"],
    allowProtocolRelative: false,
    transformTags: {
      a: sanitizeHtml.simpleTransform("a", { target: "_blank", rel: "noreferrer" }),
      input: sanitizeHtml.simpleTransform("input", { type: "checkbox", disabled: "disabled" }),
    },
  })
}
